def _fake_resolver(reject: set[str] | None = None):
    calls: list[list[str]] = []

    async def resolve(requests, engine, *, already_declared=()):  # noqa: ARG001
        calls.append([r.name for r in requests])
        out = ResolveResult()
        for r in requests:
            if reject and r.name in reject:
                out.rejected.append(Rejection(r.name, "advisory", "blocked"))
            else:
                out.packages[r.name] = ResolvedPackage(r.name, "12.40.1")
        return out

    resolve.calls = calls  # type: ignore[attr-defined]
    return resolve


async def _make_pocket(source, engine="svelte", kcb=None) -> str:
    _view, pocket_id, err = await pockets_service.agent_create(
        workspace_id="w1",
        owner_id="u1",
        name="Legacy",
        type_="site",
        pattern="landing",
        ripple_spec=None,
        engine=engine,
        source=dict(source),
        trusted=True,
        keeps_client_bundle=kcb,
    )
    assert err is None, err
    return pocket_id


async def _source(pocket_id):
    return (await pockets_service.get(pocket_id, "u1"))["source"]


async def _versions(pocket_id):
    from pocketpaw_ee.versions import service as versions

    return await versions.list_versions(scope_type="pocket", scope_id=pocket_id)


LEGACY = {
    **_PAGE,
    "package.json": _pkg(dependencies={"motion": "^12.40.0"}),
    "vite.config.ts": SVELTE_VITE,
    "src/routes/+layout.ts": "export const prerender = true;",
    "bun.lock": "{}",
}


def _run(**kw):
    kw.setdefault("_keeps_client_bundle", lambda p: p.get("keepsClientBundle") is not False)
    return run_migration(**kw)


@pytest.mark.asyncio
async def test_dry_run_reports_and_writes_nothing(beanie_test_db):
    pocket_id = await _make_pocket(LEGACY)
    before = await _versions(pocket_id)

    report = await _run(_resolve=_fake_resolver())

    assert report["mode"] == "dry_run"
    assert report["affected_pockets"] == 1 and report["migrated_pockets"] == 0
    [entry] = report["pockets"]
    classes = {row["file"]: row["class"] for row in entry["files"]}
    assert classes == {
        "bun.lock": "safe_drop",
        "package.json": "convertible",
        "src/routes/+layout.ts": "safe_drop",
        "vite.config.ts": "safe_drop",
    }
    assert await _source(pocket_id) == LEGACY
    assert len(await _versions(pocket_id)) == len(before)


@pytest.mark.asyncio
async def test_apply_migrates_records_a_draft_and_is_idempotent(beanie_test_db):
    pocket_id = await _make_pocket(LEGACY)
    before = len(await _versions(pocket_id))

    report = await _run(apply=True, _resolve=_fake_resolver())

    assert report["migrated_pockets"] == 1 and not report["errors"]
    source = await _source(pocket_id)
    assert set(source) == {*_PAGE, "paw.dependencies.json"}
    assert json.loads(source["paw.dependencies.json"])["packages"] == {
        "motion": {"version": "12.40.1"}
    }
    versions = await _versions(pocket_id)
    assert len(versions) == before + 1
    assert versions[0].author == MIGRATION_AUTHOR
    assert versions[0].status == "draft"
    assert versions[0].content == source

    again = await _run(apply=True, _resolve=_fake_resolver())
    assert again["affected_pockets"] == 0 and again["migrated_pockets"] == 0
    assert len(await _versions(pocket_id)) == before + 1


@pytest.mark.asyncio
async def test_mixed_pocket_applies_safe_files_and_keeps_review_ones(beanie_test_db):
    source = {
        **_PAGE,
        "vite.config.ts": SVELTE_VITE,
        "src/routes/+layout.ts": "export const load = () => ({ a: 1 });",
        "package.json": _pkg(dependencies={"left-pad": "^1.0.0"}),
    }
    pocket_id = await _make_pocket(source)

    report = await _run(apply=True, _resolve=_fake_resolver(reject={"left-pad"}))

    after = await _source(pocket_id)
    assert "vite.config.ts" not in after
    assert after["src/routes/+layout.ts"] == source["src/routes/+layout.ts"]
    assert after["package.json"] == source["package.json"]
    assert "paw.dependencies.json" not in after
    rows = {r["file"]: r for r in report["pockets"][0]["files"]}
    assert rows["package.json"]["class"] == "needs_review"
    assert rows["package.json"]["rejected"][0]["name"] == "left-pad"
    assert report["summary"] == {"safe_drop": 1, "convertible": 0, "needs_review": 2}


