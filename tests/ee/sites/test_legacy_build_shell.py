@pytest.mark.asyncio
async def test_runner_pages_and_resumes(beanie_test_db):
    ids = [await _make_pocket({**_PAGE, "bun.lock": "{}"}) for _ in range(3)]
    await _make_pocket({**_PAGE, "bun.lock": "{}"}, engine="html")  # html: not reserved

    first = await _run(limit=2, batch_size=1, _resolve=_fake_resolver())
    assert first["scanned"] == 2 and first["last_pocket_id"] == ids[1]
    rest = await _run(after=first["last_pocket_id"], _resolve=_fake_resolver())
    assert [p["pocket_id"] for p in rest["pockets"]] == [ids[2]]
    assert rest["scanned"] == 2  # the html pocket is scanned but has no findings


