def _one(engine, key, text, *, kcb=True, dynamic=False, extra=None):
    source = {**_PAGE, **(extra or {}), key: text}
    findings = classify_source(engine, source, keeps_client_bundle=kcb, dynamic=dynamic)
    assert [f.key for f in findings] == [key], findings
    return findings[0]


def _pkg(**over):
    pkg = json.loads(json.dumps(SVELTE_PKG))
    for k, v in over.items():
        if v is None:
            pkg.pop(k, None)
        else:
            pkg[k] = v
    return json.dumps(pkg)


